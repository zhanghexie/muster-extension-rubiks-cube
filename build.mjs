import { build } from 'esbuild';
import fs from 'node:fs/promises';
import path from 'node:path';

const root = import.meta.dirname;
const extension = path.join(root, "rubiks-cube");
const stylesheet = "styles.css";

await build({
  absWorkingDir: root,
  entryPoints: [path.join(extension, 'client/mount.jsx')],
  outfile: path.join(extension, 'ui/client.js'),
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'chrome120',
  minify: true,
  legalComments: 'eof',
  define: { 'process.env.NODE_ENV': '"production"' },
  plugins: [{
    name: 'inline-css',
    setup(builder) {
      builder.onResolve({ filter: /\.css\?inline$/ }, args => ({
        path: path.resolve(args.resolveDir, args.path.slice(0, -'?inline'.length)),
        namespace: 'inline-css',
      }));
      builder.onLoad({ filter: /.*/, namespace: 'inline-css' }, async args => ({
        contents: (await fs.readFile(args.path, 'utf8')).replace(/\r\n/g, '\n'),
        loader: 'text',
      }));
    },
  }],
});
const [shared, local] = await Promise.all([
  fs.readFile(path.join(root, 'support/styles.css'), 'utf8'),
  fs.readFile(path.join(extension, 'client', stylesheet), 'utf8'),
]);
await fs.writeFile(path.join(extension, 'ui', stylesheet), '/* Generated by build.mjs */\n' + shared + local);
